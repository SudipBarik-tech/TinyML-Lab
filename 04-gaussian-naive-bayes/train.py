from pathlib import Path

import numpy as np
from sklearn.datasets import make_classification
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split
from sklearn.naive_bayes import GaussianNB

SEED = 42
OUT = Path(__file__).parent / "embedded" / "generated_gnb.h"


def format_array(values) -> str:
    return ", ".join(f"{float(v):.9f}f" for v in values)


def model_to_c(model: GaussianNB) -> str:
    n_classes, n_features = model.theta_.shape
    means = ",\n    ".join("{" + format_array(row) + "}" for row in model.theta_)
    variances = ",\n    ".join("{" + format_array(row) + "}" for row in model.var_)
    priors = format_array(model.class_prior_)

    return f"""#pragma once
#include <math.h>

// Generated by 04-gaussian-naive-bayes/train.py
constexpr int GNB_CLASSES = {n_classes};
constexpr int GNB_FEATURES = {n_features};

static const float GNB_MEAN[GNB_CLASSES][GNB_FEATURES] = {{
    {means}
}};

static const float GNB_VAR[GNB_CLASSES][GNB_FEATURES] = {{
    {variances}
}};

static const float GNB_PRIOR[GNB_CLASSES] = {{{priors}}};

inline int predictGaussianNB(const float *x) {{
    int bestClass = 0;
    float bestScore = -INFINITY;

    for (int c = 0; c < GNB_CLASSES; ++c) {{
        float score = logf(GNB_PRIOR[c]);
        for (int f = 0; f < GNB_FEATURES; ++f) {{
            const float var = GNB_VAR[c][f];
            const float diff = x[f] - GNB_MEAN[c][f];
            score += -0.5f * logf(2.0f * PI * var) - (diff * diff) / (2.0f * var);
        }}
        if (score > bestScore) {{
            bestScore = score;
            bestClass = c;
        }}
    }}
    return bestClass;
}}
"""


def main() -> None:
    X, y = make_classification(
        n_samples=700,
        n_features=3,
        n_informative=3,
        n_redundant=0,
        n_clusters_per_class=1,
        class_sep=1.25,
        random_state=SEED,
    )
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.25, stratify=y, random_state=SEED
    )

    model = GaussianNB()
    model.fit(X_train, y_train)

    prediction = model.predict(X_test)
    print(f"Test accuracy: {accuracy_score(y_test, prediction):.4f}")
    print("Class means:\n", np.round(model.theta_, 4))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(model_to_c(model), encoding="utf-8")
    print(f"Generated: {OUT}")


if __name__ == "__main__":
    main()
