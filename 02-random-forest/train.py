from pathlib import Path

from sklearn.datasets import make_classification
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split

SEED = 42
OUT = Path(__file__).parent / "embedded" / "generated_forest.h"


def export_tree(tree, function_name: str) -> str:
    def emit(node: int, depth: int = 1) -> list[str]:
        pad = "    " * depth
        if tree.children_left[node] == tree.children_right[node]:
            cls = int(tree.value[node][0].argmax())
            return [f"{pad}return {cls};"]

        feature = tree.feature[node]
        threshold = tree.threshold[node]
        lines = [f"{pad}if (x[{feature}] <= {threshold:.8f}f) {{"]
        lines += emit(tree.children_left[node], depth + 1)
        lines.append(f"{pad}}} else {{")
        lines += emit(tree.children_right[node], depth + 1)
        lines.append(f"{pad}}}")
        return lines

    return f"inline int {function_name}(const float *x) {{\n" + "\n".join(emit(0)) + "\n}\n"


def forest_to_c(model: RandomForestClassifier) -> str:
    functions = []
    calls = []
    for index, estimator in enumerate(model.estimators_):
        name = f"tree_{index}"
        functions.append(export_tree(estimator.tree_, name))
        calls.append(f"    votes += {name}(x);\n")

    threshold = len(model.estimators_) // 2 + 1
    return (
        "#pragma once\n\n// Generated by 02-random-forest/train.py\n\n"
        + "\n".join(functions)
        + "\ninline int predictRandomForest(const float *x) {\n"
        + "    int votes = 0;\n"
        + "".join(calls)
        + f"    return votes >= {threshold} ? 1 : 0;\n"
        + "}\n"
    )


def main() -> None:
    X, y = make_classification(
        n_samples=800,
        n_features=3,
        n_informative=3,
        n_redundant=0,
        class_sep=1.1,
        random_state=SEED,
    )
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.25, stratify=y, random_state=SEED
    )

    model = RandomForestClassifier(
        n_estimators=7,
        max_depth=3,
        min_samples_leaf=8,
        random_state=SEED,
    )
    model.fit(X_train, y_train)

    prediction = model.predict(X_test)
    print(f"Test accuracy: {accuracy_score(y_test, prediction):.4f}")
    print(f"Trees: {len(model.estimators_)}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(forest_to_c(model), encoding="utf-8")
    print(f"Generated: {OUT}")


if __name__ == "__main__":
    main()
