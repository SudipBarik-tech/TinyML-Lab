import json
from pathlib import Path

import xgboost as xgb
from sklearn.datasets import make_classification
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split

SEED = 42
OUT = Path(__file__).parent / "embedded" / "generated_xgb.h"


def emit_node(node: dict, depth: int = 1) -> list[str]:
    pad = "    " * depth
    if "leaf" in node:
        return [f"{pad}return {float(node['leaf']):.9f}f;"]

    feature = int(str(node["split"]).replace("f", ""))
    threshold = float(node["split_condition"])
    yes_id = node["yes"]
    no_id = node["no"]
    children = {child["nodeid"]: child for child in node["children"]}

    lines = [f"{pad}if (x[{feature}] < {threshold:.9f}f) {{"]
    lines += emit_node(children[yes_id], depth + 1)
    lines.append(f"{pad}}} else {{")
    lines += emit_node(children[no_id], depth + 1)
    lines.append(f"{pad}}}")
    return lines


def model_to_c(model: xgb.XGBClassifier) -> str:
    dumps = model.get_booster().get_dump(dump_format="json")
    functions = []
    calls = []

    for index, raw_tree in enumerate(dumps):
        tree = json.loads(raw_tree)
        name = f"xgb_tree_{index}"
        body = "\n".join(emit_node(tree))
        functions.append(f"inline float {name}(const float *x) {{\n{body}\n}}\n")
        calls.append(f"    score += {name}(x);\n")

    return (
        "#pragma once\n\n"
        "// Generated by 03-xgboost/train.py.\n"
        "// The model uses the default binary-logistic base score of 0.5,\n"
        "// corresponding to an initial logit margin of 0.\n\n"
        + "\n".join(functions)
        + "\ninline int predictXGBoost(const float *x) {\n"
        + "    float score = 0.0f;\n"
        + "".join(calls)
        + "    return score >= 0.0f ? 1 : 0;\n"
        + "}\n"
    )


def main() -> None:
    X, y = make_classification(
        n_samples=800,
        n_features=4,
        n_informative=4,
        n_redundant=0,
        n_clusters_per_class=1,
        class_sep=1.15,
        random_state=SEED,
    )
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.25, stratify=y, random_state=SEED
    )

    model = xgb.XGBClassifier(
        n_estimators=6,
        max_depth=2,
        learning_rate=0.30,
        subsample=1.0,
        colsample_bytree=1.0,
        objective="binary:logistic",
        eval_metric="logloss",
        random_state=SEED,
        n_jobs=1,
    )
    model.fit(X_train, y_train)

    prediction = model.predict(X_test)
    print(f"Test accuracy: {accuracy_score(y_test, prediction):.4f}")
    print(f"Boosted trees: {model.n_estimators}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(model_to_c(model), encoding="utf-8")
    print(f"Generated: {OUT}")


if __name__ == "__main__":
    main()
