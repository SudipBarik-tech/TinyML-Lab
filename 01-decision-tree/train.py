from pathlib import Path

from sklearn.datasets import make_classification
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier

SEED = 42
OUT = Path(__file__).parent / "embedded" / "generated_model.h"


def tree_to_c(model: DecisionTreeClassifier) -> str:
    tree = model.tree_

    def emit(node: int, depth: int = 1) -> list[str]:
        pad = "    " * depth
        if tree.children_left[node] == tree.children_right[node]:
            cls = int(tree.value[node][0].argmax())
            return [f"{pad}return {cls};"]

        feature = tree.feature[node]
        threshold = tree.threshold[node]
        lines = [f"{pad}if (x[{feature}] <= {threshold:.8f}f) {{"]
        lines += emit(tree.children_left[node], depth + 1)
        lines.append(f"{pad}}} else {{")
        lines += emit(tree.children_right[node], depth + 1)
        lines.append(f"{pad}}}")
        return lines

    body = "\n".join(emit(0))
    return f"""#pragma once

// Generated by 01-decision-tree/train.py
inline int predictDecisionTree(const float *x) {{
{body}
}}
"""


def main() -> None:
    X, y = make_classification(
        n_samples=600,
        n_features=2,
        n_informative=2,
        n_redundant=0,
        n_clusters_per_class=1,
        class_sep=1.2,
        random_state=SEED,
    )
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.25, stratify=y, random_state=SEED
    )

    model = DecisionTreeClassifier(max_depth=3, min_samples_leaf=8, random_state=SEED)
    model.fit(X_train, y_train)

    prediction = model.predict(X_test)
    print(f"Test accuracy: {accuracy_score(y_test, prediction):.4f}")
    print(f"Tree depth: {model.get_depth()}")
    print(f"Leaf count: {model.get_n_leaves()}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(tree_to_c(model), encoding="utf-8")
    print(f"Generated: {OUT}")


if __name__ == "__main__":
    main()
